# Шаблоны телефонов
PHONE_PREFIXES = ["+7 (495)", "+7 (812)", "+7 (383)", "+7 (391)", "+7 (343)"]
PHONE_SUFFIX = lambda: f"{random.randint(100, 999)}-{random.randint(10, 99)}-{random.randint(10, 99)}"


def generate_phone():
    return f"{random.choice(PHONE_PREFIXES)} {PHONE_SUFFIX()}"


def generate_email(name, company_num):
    domains = ["mail.ru", "yandex.ru", "expert.ru", "company.ru"]
    translit = {"а": "a", "б": "b", "в": "v", "г": "g", "д": "d", "е": "e", "ё": "e",
                "ж": "zh", "з": "z", "и": "i", "й": "y", "к": "k", "л": "l", "м": "m",
                "н": "n", "о": "o", "п": "p", "р": "r", "с": "s", "т": "t", "у": "u",
                "ф": "f", "х": "h", "ц": "ts", "ч": "ch", "ш": "sh", "щ": "sch",
                "ъ": "", "ы": "y", "ь": "", "э": "e", "ю": "yu", "я": "ya"}
    parts = name.split()[0].lower()
    base = "".join(translit.get(c, c) for c in parts if c.isalpha())[:8]
    return f"{base}{company_num}@{random.choice(domains)}"


def main():
    mgr = ExpertsManager()
    
    # Проверяем, сколько уже есть
    existing = mgr.get_count()
    if existing >= 50:
        print(f"Уже есть {existing} экспертов. Добавить ещё? Пропускаем для избежания дублей.")
        return
    
    to_add = 50 - existing
    names_to_use = EXPERT_NAMES[:to_add] if existing == 0 else random.sample(EXPERT_NAMES, min(to_add, len(EXPERT_NAMES)))
    
    if existing > 0:
        # Берём те имена, которых ещё нет
        all_experts = mgr.get_all()
        existing_names = {e.get('name') for e in all_experts}
        names_to_use = [n for n in EXPERT_NAMES if n not in existing_names][:to_add]
    
    if not names_to_use:
        print("Нет новых имён для добавления.")
        return
    
    print(f"Добавляем {len(names_to_use)} экспертов...")
    
    for i, expert_name in enumerate(names_to_use):
        expert_id = mgr.add_expert(expert_name)
        if not expert_id:
            print(f"  Ошибка добавления: {expert_name}")
            continue
        
        # 1-3 контакта на эксперта
        num_contacts = random.randint(1, 3)
        for j in range(num_contacts):
            first = random.choice(CONTACT_FIRST_NAMES)
            last = random.choice(CONTACT_LAST_NAMES)
            full_name = f"{last} {first} {random.choice(CONTACT_PATRONYMICS)}"
            position = random.choice(POSITIONS)
            phone = generate_phone()
            email = generate_email(full_name, expert_id)
            is_primary = (j == 0)
            mgr.add_contact(expert_id, full_name, position, phone, email, is_primary)
        
        # 2-4 специализации на эксперта
        specs = random.sample(SPECIALIZATIONS, random.randint(2, 4))
        for spec in specs:
            mgr.add_specialization(expert_id, spec)
        
        print(f"  [{i+1}/{len(names_to_use)}] {expert_name[:40]}... (ID={expert_id})")
    
    total = mgr.get_count()
    print(f"\nГотово! Всего экспертов в БД: {total}")


if __name__ == "__main__":
    main()
